with open(BASE_DIR / "data" / "processed" / "coverage_results_FINAL.csv", encoding="utf-8-sig") as f:
    rows = {r["location_day_id"]: r for r in csv.DictReader(f)}
with open(BASE_DIR / "scripts" / "uncovered_audit_sample_ids.txt", encoding="utf-8") as f:
    sample_ids = [l.strip() for l in f if l.strip()]

with (BASE_DIR / "scripts" / "25_uncovered_audit.progress.log").open("w", encoding="utf-8") as log:
    for ldid in sample_ids:
        r = rows.get(ldid)
        if not r:
            log.write(f"{ldid.encode('ascii','backslashreplace').decode('ascii')}: NOT FOUND\n")
            continue
        event_date = dt.date.fromisoformat(r["event_date"])
        end7 = event_date + dt.timedelta(days=7)

        extras = EXTRA_VARIANTS.get(ldid, [])
        base_query = r["query_used"].split(" | fallback:")[0].replace("base:", "").strip()
        # build an alt query: original alias clause OR'd with the new extra variants
        if extras:
            extra_clause = " OR ".join(f'"{e}"' for e in extras)
            # splice extras into the alias parenthetical if present, else just AND them in
            if base_query.startswith("("):
                close_idx = base_query.index(")")
                alt_query = base_query[:close_idx] + f' OR {extra_clause}' + base_query[close_idx:]
            else:
                alt_query = f'({extra_clause}) AND Lebanon'
        else:
            alt_query = base_query

        try:
            page, _ = with_retry(lambda: search.story_list(alt_query, start_date=event_date, end_date=end7, collection_ids=[COLLECTION_ID], page_size=10))
        except Exception as e:
            log.write(f"{ldid.encode('ascii','backslashreplace').decode('ascii')}: ERROR {e}\n\n")
            continue

        log.write(f"{ldid.encode('ascii','backslashreplace').decode('ascii')} | extras={extras} | n_d7={len(page)}\n")
        log.write(f"  query: {alt_query}\n")
        for s in page[:5]:
            log.write(f"    [{s.get('media_name','')}] {s.get('title','').encode('ascii','backslashreplace').decode('ascii')} | {s.get('publish_date','')}\n")
        log.write("\n")
        time.sleep(1.2)

    log.write("=== done ===\n")
