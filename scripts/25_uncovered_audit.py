def with_retry(fn, max_attempts=6):
    delay = 4.0
    for attempt in range(max_attempts):
        try:
            return fn()
        except Exception as e:
            if "429" in str(e) and attempt < max_attempts - 1:
                time.sleep(delay)
                delay = min(delay * 1.8, 25)
                continue
            raise
    return None


